"""Produce docs/demo/walkthrough.md: two fictional reports, a status transition with HITL approval,
a multi-stage RAG query, and audit records. Uses an isolated temp DB (never logs/app.db)."""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pharma_intake import audit, config, db, repository, workflow  # noqa: E402
from pharma_intake.agent.orchestrator import Orchestrator  # noqa: E402
from pharma_intake.agent.tools import AgentContext  # noqa: E402
from pharma_intake.rag.pipeline import build_retriever  # noqa: E402
from pharma_intake.schemas import Status  # noqa: E402
from pharma_intake.validation import validate_intake  # noqa: E402

conn = db.connect(Path(tempfile.mkdtemp()) / "demo.db")
out: list[str] = ["# Demo walkthrough (generated by scripts/generate_demo.py)", "",
                  "All data is fictional. Isolated temp database; models run locally/offline.", ""]

# 1. Two fictional reports
out += ["## 1. Two fictional reports", ""]
refs = []
for raw in json.loads(config.SEED_REPORTS.read_text(encoding="utf-8"))[:2]:
    outcome = validate_intake(raw)
    ref = repository.create_report(conn, outcome.model, actor="intake-operator")
    refs.append(ref)
    out.append(f"- **{ref}** - {raw['report_type']} - {raw['product_name']} - {raw['batch_id']}")

out += ["", "### Validation demo (nothing saved)", ""]
bad = validate_intake({**json.loads(config.SEED_REPORTS.read_text(encoding="utf-8"))[0], "batch_id": "lot 123", "event_onset_date": None})
out += [f"- {e}" for e in bad.errors] + [f"- (auto-repair note) {r}" for r in bad.repairs]

# 2. Status transition with HITL gate
out += ["", "## 2. Status transition with human approval", ""]
workflow.request_transition(conn, refs[0], Status.IN_REVIEW, "REV-01")
out.append(f"- {refs[0]}: New -> In Review (REV-01)")
r = workflow.request_transition(conn, refs[0], Status.CLOSED, "REV-01")
out.append(f"- {refs[0]}: closure requested -> pending_approval={r['pending_approval']}, status still '{repository.get_report(conn, refs[0])['status']}' (frozen)")
try:
    workflow.request_transition(conn, refs[0], Status.CLOSED, "REV-01")
except workflow.ReportFrozen as exc:
    out.append(f"- second request refused: {exc}")
workflow.decide_approval(conn, refs[0], "REV-02", True)
out.append(f"- REV-02 approved -> status '{repository.get_report(conn, refs[0])['status']}'")

# 3. Multi-stage RAG query
out += ["", "## 3. Multi-stage RAG query: `difficulty breathing`", ""]
retriever = build_retriever(conn)
res = retriever.search("difficulty breathing")
st = res.stages
dense = ", ".join("%s (%s)" % (x["chunk_id"], x["score"]) for x in st["stage2_dense"][:3])
scored = ", ".join("%s (%s)" % (x["chunk_id"], x["rerank"]) for x in st["stage4_scored"][:3])
lexical = ", ".join(x["chunk_id"] for x in st["stage1_bm25"][:3]) or "(no lexical overlap)"
rrf_top = ", ".join(x["chunk_id"] for x in st["stage3_rrf_top"][:3])
out += ["| Stage | Top results |", "|---|---|",
        f"| 1 BM25 (k1={config.BM25_K1}, b={config.BM25_B}) | {lexical} |",
        f"| 2 Bi-encoder cosine | {dense} |",
        f"| 3 RRF k={config.RRF_K} | pool={st['stage3_rrf_pool_size']}; top: {rrf_top} |",
        f"| 4 Cross-encoder (threshold {config.RERANK_THRESHOLD}) | {scored}; kept={st['stage4_kept']} |",
        "", "```", res.answer, "```", ""]
none = retriever.search("quarterly cafeteria menu zebra")
out += ["Unrelated query (`quarterly cafeteria menu zebra`) -> kept chunks: " + str(len(none.hits)) + f" -> \"{none.answer[:70]}...\"", ""]

# 4. Agent control plane
out += ["## 4. Agent control plane", ""]
orch = Orchestrator(AgentContext(conn, retriever_factory=lambda: build_retriever(conn)))
for q in ["Did the drug cause the anaphylaxis?", f"close {refs[1]} reviewer REV-01", f"move {refs[1]} to in review reviewer rev 1"]:
    run = orch.handle(q)
    out.append(f"- `{q}` -> route **{run.route.value}** -> {run.reply.splitlines()[0][:110]}")

# 5. Audit records
ok, bad_id = audit.verify_chain(conn)
out += ["", "## 5. Audit records", "", f"Hash chain verified: **{ok}**", "",
        "| id | ts_utc | actor | action | ref_id | from | to | fields |", "|---|---|---|---|---|---|---|---|"]
for e in audit.list_events(conn):
    out.append(f"| {e['id']} | {e['ts_utc']} | {e['actor']} | {e['action']} | {e['ref_id'] or ''} | {e['from_status'] or ''} | {e['to_status'] or ''} | {e['fields'] or ''} |")

dest = ROOT / "docs" / "demo"
dest.mkdir(parents=True, exist_ok=True)
(dest / "walkthrough.md").write_text("\n".join(out) + "\n", encoding="utf-8")

hook_log = config.LOGS_DIR / "claude_edit_audit.jsonl"
if hook_log.exists():
    lines = hook_log.read_text(encoding="utf-8").splitlines()
    (dest / "hook_audit_excerpt.jsonl").write_text("\n".join(lines[:10] + lines[-5:]) + "\n", encoding="utf-8")
print(f"Wrote {dest / 'walkthrough.md'}")
